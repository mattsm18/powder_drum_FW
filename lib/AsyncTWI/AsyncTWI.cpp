#include "AsyncTWI.h"

///////////////////////////////////////////////////////////////////////////////////////////////////
// begin
///////////////////////////////////////////////////////////////////////////////////////////////////

void AsyncTWI::begin(uint32_t frequency)
{
    _frequency = frequency;

    recoverPeripheral();

    initialisePeripheral();

    _transaction = Transaction::NONE;
    _state = State::IDLE;
    _result = Result::NONE;

    _address = 0;
    _register = 0;

    _readBuffer = nullptr;
    _writeBuffer = nullptr;

    _length = 0;
    _index = 0;

    _stateStart_us = micros();
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// initialisePeripheral
///////////////////////////////////////////////////////////////////////////////////////////////////

void AsyncTWI::initialisePeripheral()
{
    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Disable TWI while configuring.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    TWI0.MCTRLA = 0;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Nano Every / ATmega4809
    //
    // TWI0 default route:
    //
    //     PA2 = SDA
    //     PA3 = SCL
    //
    // Configure pins as inputs.
    //
    // External I2C pull-ups should be used.
    //
    ///////////////////////////////////////////////////////////////////////////////////////////////

    pinMode(SDA, INPUT);
    pinMode(SCL, INPUT);

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Explicitly select TWI0 default route.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    PORTMUX.TWISPIROUTEA =
        (PORTMUX.TWISPIROUTEA & ~PORTMUX_TWI0_gm) |
        PORTMUX_TWI0_DEFAULT_gc;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // TWI baud rate.
    //
    // F_CPU = 16 MHz
    // Target = 100 kHz
    //
    // BAUD = (F_CPU / F_SCL - 10) / 2
    //
    // = (160 - 10) / 2
    // = 75
    //
    ///////////////////////////////////////////////////////////////////////////////////////////////

    uint32_t baud =
        ((F_CPU / _frequency) - 10UL) / 2UL;

    if (baud > 255UL)
    {
        baud = 255UL;
    }

    TWI0.MBAUD =
        static_cast<uint8_t>(baud);

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Enable TWI master.
    //
    // Hardware timeout is enabled at 100 us.
    //
    // This prevents the TWI peripheral itself from remaining indefinitely
    // in an inactive bus state.
    //
    ///////////////////////////////////////////////////////////////////////////////////////////////

    TWI0.MCTRLA =
        TWI_TIMEOUT_100US_gc |
        TWI_ENABLE_bm;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Put master into IDLE bus state.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    TWI0.MSTATUS =
        TWI_BUSSTATE_IDLE_gc;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// readRegisters
///////////////////////////////////////////////////////////////////////////////////////////////////

bool AsyncTWI::readRegisters(
    uint8_t address,
    uint8_t reg,
    uint8_t* buffer,
    uint8_t length
)
{
    if (isBusy())
    {
        return false;
    }

    if (buffer == nullptr)
    {
        return false;
    }

    if (length == 0)
    {
        return false;
    }

    ///////////////////////////////////////////////////////////////////////////////////////////////

    _transaction =
        Transaction::READ;

    _address =
        address;

    _register =
        reg;

    _readBuffer =
        buffer;

    _writeBuffer =
        nullptr;

    _length =
        length;

    _index =
        0;

    _result =
        Result::BUSY;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Start with SLA+W.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    setState(
        State::START_WRITE
    );

    return true;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// writeRegisters
///////////////////////////////////////////////////////////////////////////////////////////////////

bool AsyncTWI::writeRegisters(
    uint8_t address,
    uint8_t reg,
    const uint8_t* buffer,
    uint8_t length
)
{
    if (isBusy())
    {
        return false;
    }

    if (buffer == nullptr)
    {
        return false;
    }

    if (length == 0)
    {
        return false;
    }

    ///////////////////////////////////////////////////////////////////////////////////////////////

    _transaction =
        Transaction::WRITE;

    _address =
        address;

    _register =
        reg;

    _readBuffer =
        nullptr;

    _writeBuffer =
        buffer;

    _length =
        length;

    _index =
        0;

    _result =
        Result::BUSY;

    ///////////////////////////////////////////////////////////////////////////////////////////////

    setState(
        State::START_WRITE
    );

    return true;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// update
///////////////////////////////////////////////////////////////////////////////////////////////////

void AsyncTWI::update()
{
    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Nothing to do.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    if (_state == State::IDLE ||
        _state == State::COMPLETE ||
        _state == State::ERROR)
    {
        return;
    }

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Software timeout.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    if (timedOut())
    {
        fail(Result::TIMEOUT);
        return;
    }

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Hardware error detection.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    if (checkHardwareError())
    {
        return;
    }

    ///////////////////////////////////////////////////////////////////////////////////////////////

    const uint8_t status =
        TWI0.MSTATUS;

    switch (_state)
    {
        ///////////////////////////////////////////////////////////////////////////////////////////
        // Generate START + SLA+W
        ///////////////////////////////////////////////////////////////////////////////////////////

        case State::START_WRITE:
        {
            TWI0.MADDR =
                static_cast<uint8_t>(
                    (_address << 1) & 0xFE
                );

            setState(
                State::WAIT_WRITE_ADDRESS
            );

            break;
        }

        ///////////////////////////////////////////////////////////////////////////////////////////
        // Wait for SLA+W
        ///////////////////////////////////////////////////////////////////////////////////////////

        case State::WAIT_WRITE_ADDRESS:
        {
            if (!(status & TWI_WIF_bm))
            {
                return;
            }

            if (status & TWI_RXACK_bm)
            {
                fail(Result::NACK);
                return;
            }

            // Slave acknowledged.
            //
            // Send register address.

            TWI0.MDATA =
                _register;

            setState(
                State::WAIT_REGISTER
            );

            break;
        }

        ///////////////////////////////////////////////////////////////////////////////////////////
        // Wait for register address
        ///////////////////////////////////////////////////////////////////////////////////////////

        case State::WAIT_REGISTER:
        {
            if (!(status & TWI_WIF_bm))
            {
                return;
            }

            if (status & TWI_RXACK_bm)
            {
                fail(Result::NACK);
                return;
            }

            ///////////////////////////////////////////////////////////////////////////////
            // WRITE
            ///////////////////////////////////////////////////////////////////////////////

            if (_transaction == Transaction::WRITE)
            {
                _index = 0;

                TWI0.MDATA =
                    _writeBuffer[_index];

                _index++;

                setState(
                    State::WAIT_WRITE_DATA
                );

                return;
            }

            ///////////////////////////////////////////////////////////////////////////////
            // READ
            //
            // Issue repeated START + SLA+R.
            ///////////////////////////////////////////////////////////////////////////////

            TWI0.MADDR =
                static_cast<uint8_t>(
                    (_address << 1) | 0x01
                );

            setState(
                State::WAIT_READ_ADDRESS
            );

            break;
        }

        ///////////////////////////////////////////////////////////////////////////////////////////
        // Wait for write data
        ///////////////////////////////////////////////////////////////////////////////////////////

        case State::WAIT_WRITE_DATA:
        {
            if (!(status & TWI_WIF_bm))
            {
                return;
            }

            if (status & TWI_RXACK_bm)
            {
                fail(Result::NACK);
                return;
            }

            ///////////////////////////////////////////////////////////////////////////////
            // More data?
            ///////////////////////////////////////////////////////////////////////////////

            if (_index < _length)
            {
                TWI0.MDATA =
                    _writeBuffer[_index];

                _index++;

                return;
            }

            ///////////////////////////////////////////////////////////////////////////////
            // Finished.
            ///////////////////////////////////////////////////////////////////////////////

            TWI0.MCTRLB =
                TWI_MCMD_STOP_gc;

            complete();

            break;
        }

        ///////////////////////////////////////////////////////////////////////////////////////////
        // Wait for SLA+R
        ///////////////////////////////////////////////////////////////////////////////////////////

        case State::WAIT_READ_ADDRESS:
        {
            ///////////////////////////////////////////////////////////////////////////////
            // During a read transaction RIF indicates that received data
            // is available.
            //
            // If WIF is set here, the address phase resulted in a NACK.
            ///////////////////////////////////////////////////////////////////////////////

            if (status & TWI_WIF_bm)
            {
                if (status & TWI_RXACK_bm)
                {
                    fail(Result::NACK);
                }
                else
                {
                    fail(Result::BUS_ERROR);
                }

                return;
            }

            if (!(status & TWI_RIF_bm))
            {
                return;
            }

            ///////////////////////////////////////////////////////////////////////////////
            // First byte.
            ///////////////////////////////////////////////////////////////////////////////

            _readBuffer[0] =
                TWI0.MDATA;

            _index = 1;

            ///////////////////////////////////////////////////////////////////////////////
            // One-byte read.
            ///////////////////////////////////////////////////////////////////////////////

            if (_index >= _length)
            {
                TWI0.MCTRLB =
                    TWI_ACKACT_bm |
                    TWI_MCMD_STOP_gc;

                complete();

                return;
            }

            ///////////////////////////////////////////////////////////////////////////////
            // More bytes required.
            //
            // ACK current byte and request another.
            ///////////////////////////////////////////////////////////////////////////////

            TWI0.MCTRLB =
                TWI_MCMD_RECVTRANS_gc;

            setState(
                State::READ_DATA
            );

            break;
        }

        ///////////////////////////////////////////////////////////////////////////////////////////
        // Read data
        ///////////////////////////////////////////////////////////////////////////////////////////

        case State::READ_DATA:
        {
            if (!(status & TWI_RIF_bm))
            {
                return;
            }

            ///////////////////////////////////////////////////////////////////////////////
            // Store byte.
            ///////////////////////////////////////////////////////////////////////////////

            _readBuffer[_index] =
                TWI0.MDATA;

            _index++;

            ///////////////////////////////////////////////////////////////////////////////
            // Last byte.
            ///////////////////////////////////////////////////////////////////////////////

            if (_index >= _length)
            {
                // NACK final byte + STOP.

                TWI0.MCTRLB =
                    TWI_ACKACT_bm |
                    TWI_MCMD_STOP_gc;

                complete();

                return;
            }

            ///////////////////////////////////////////////////////////////////////////////
            // Continue receiving.
            ///////////////////////////////////////////////////////////////////////////////

            TWI0.MCTRLB =
                TWI_MCMD_RECVTRANS_gc;

            break;
        }

        ///////////////////////////////////////////////////////////////////////////////////////////

        default:
        {
            fail(Result::BUS_ERROR);
            break;
        }
    }
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// Hardware error checking
///////////////////////////////////////////////////////////////////////////////////////////////////

bool AsyncTWI::checkHardwareError()
{
    const uint8_t status =
        TWI0.MSTATUS;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Arbitration lost
    ///////////////////////////////////////////////////////////////////////////////////////////////

    if (status & TWI_ARBLOST_bm)
    {
        fail(Result::ARBITRATION_LOST);
        return true;
    }

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Bus error
    ///////////////////////////////////////////////////////////////////////////////////////////////

    if (status & TWI_BUSERR_bm)
    {
        fail(Result::BUS_ERROR);
        return true;
    }

    return false;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// State transition
///////////////////////////////////////////////////////////////////////////////////////////////////

void AsyncTWI::setState(State state)
{
    _state =
        state;

    _stateStart_us =
        micros();
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// Timeout
///////////////////////////////////////////////////////////////////////////////////////////////////

bool AsyncTWI::timedOut() const
{
    return
        static_cast<uint32_t>(
            micros() - _stateStart_us
        ) >= STATE_TIMEOUT_US;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// Complete
///////////////////////////////////////////////////////////////////////////////////////////////////

void AsyncTWI::complete()
{
    _result =
        Result::OK;

    _state =
        State::COMPLETE;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// Fail
///////////////////////////////////////////////////////////////////////////////////////////////////

void AsyncTWI::fail(Result result)
{
    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Request STOP.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    TWI0.MCTRLB =
        TWI_MCMD_STOP_gc;

    _result =
        result;

    _state =
        State::ERROR;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// isBusy
///////////////////////////////////////////////////////////////////////////////////////////////////

bool AsyncTWI::isBusy() const
{
    return
        _state != State::IDLE &&
        _state != State::COMPLETE &&
        _state != State::ERROR;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// isDone
///////////////////////////////////////////////////////////////////////////////////////////////////

bool AsyncTWI::isDone() const
{
    return
        _state == State::COMPLETE ||
        _state == State::ERROR;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// getResult
///////////////////////////////////////////////////////////////////////////////////////////////////

AsyncTWI::Result AsyncTWI::getResult() const
{
    return _result;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// getState
///////////////////////////////////////////////////////////////////////////////////////////////////

uint8_t AsyncTWI::getState() const
{
    return static_cast<uint8_t>(_state);
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// getHardwareStatus
///////////////////////////////////////////////////////////////////////////////////////////////////

uint8_t AsyncTWI::getHardwareStatus() const
{
    return TWI0.MSTATUS;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// clearDone
///////////////////////////////////////////////////////////////////////////////////////////////////

void AsyncTWI::clearDone()
{
    if (!isDone())
    {
        return;
    }

    _transaction =
        Transaction::NONE;

    _state =
        State::IDLE;

    _result =
        Result::NONE;

    _address =
        0;

    _register =
        0;

    _readBuffer =
        nullptr;

    _writeBuffer =
        nullptr;

    _length =
        0;

    _index =
        0;
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// reset
///////////////////////////////////////////////////////////////////////////////////////////////////

void AsyncTWI::reset()
{
    recoverPeripheral();

    initialisePeripheral();

    _transaction =
        Transaction::NONE;

    _state =
        State::IDLE;

    _result =
        Result::NONE;

    _address =
        0;

    _register =
        0;

    _readBuffer =
        nullptr;

    _writeBuffer =
        nullptr;

    _length =
        0;

    _index =
        0;

    _stateStart_us =
        micros();
}

///////////////////////////////////////////////////////////////////////////////////////////////////
// Recover peripheral
///////////////////////////////////////////////////////////////////////////////////////////////////

void AsyncTWI::recoverPeripheral()
{
    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Disable peripheral.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    TWI0.MCTRLA = 0;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Flush master state.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    TWI0.MCTRLB =
        TWI_FLUSH_bm;
}