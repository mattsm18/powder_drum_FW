#pragma once

#include <Arduino.h>

///////////////////////////////////////////////////////////////////////////////////////////////////
// AsyncTWI
//
// Non-blocking TWI/I2C master for ATmega4809 / Arduino Nano Every.
//
// Design:
//
//     readRegisters()
//             |
//             v
//         transaction
//             |
//             v
//          update()
//             |
//             v
//       hardware state machine
//
// update() NEVER waits for the TWI peripheral.
//
// Call update() frequently from the main loop.
//
// Example AS5600 read:
//
//     START
//     SLA+W
//     REGISTER
//     REPEATED START
//     SLA+R
//     DATA
//     DATA
//     NACK
//     STOP
//
///////////////////////////////////////////////////////////////////////////////////////////////////

class AsyncTWI
{
public:

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Transaction result
    ///////////////////////////////////////////////////////////////////////////////////////////////

    enum class Result : uint8_t
    {
        NONE = 0,
        BUSY,
        OK,
        NACK,
        BUS_ERROR,
        ARBITRATION_LOST,
        TIMEOUT
    };

    ///////////////////////////////////////////////////////////////////////////////////////////////

    AsyncTWI() = default;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Initialise peripheral
    //
    // frequency:
    //     TWI clock frequency in Hz.
    //
    // Typical:
    //     100000 Hz
    //
    ///////////////////////////////////////////////////////////////////////////////////////////////

    void begin(uint32_t frequency = 100000UL);

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Start asynchronous register read
    //
    // address:
    //     7-bit I2C address.
    //
    // reg:
    //     Register address.
    //
    // buffer:
    //     Destination buffer.
    //
    // length:
    //     Number of bytes to read.
    //
    ///////////////////////////////////////////////////////////////////////////////////////////////

    bool readRegisters(
        uint8_t address,
        uint8_t reg,
        uint8_t* buffer,
        uint8_t length
    );

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Start asynchronous register write
    //
    // address:
    //     7-bit I2C address.
    //
    // reg:
    //     Register address.
    //
    // buffer:
    //     Source buffer.
    //
    // length:
    //     Number of bytes to write.
    //
    ///////////////////////////////////////////////////////////////////////////////////////////////

    bool writeRegisters(
        uint8_t address,
        uint8_t reg,
        const uint8_t* buffer,
        uint8_t length
    );

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Advance transaction state machine.
    //
    // Call this frequently.
    //
    // This function does not wait for hardware.
    //
    ///////////////////////////////////////////////////////////////////////////////////////////////

    void update();

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Status
    ///////////////////////////////////////////////////////////////////////////////////////////////

    bool isBusy() const;

    bool isDone() const;

    Result getResult() const;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Debug
    ///////////////////////////////////////////////////////////////////////////////////////////////

    uint8_t getState() const;

    uint8_t getHardwareStatus() const;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Clear completed transaction.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    void clearDone();

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Abort current transaction and reset peripheral.
    ///////////////////////////////////////////////////////////////////////////////////////////////

    void reset();

private:

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Transaction type
    ///////////////////////////////////////////////////////////////////////////////////////////////

    enum class Transaction : uint8_t
    {
        NONE,
        READ,
        WRITE
    };

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // State machine
    ///////////////////////////////////////////////////////////////////////////////////////////////

    enum class State : uint8_t
    {
        IDLE = 0,

        START_WRITE,

        WAIT_WRITE_ADDRESS,

        WRITE_REGISTER,

        WAIT_REGISTER,

        WRITE_DATA,

        WAIT_WRITE_DATA,

        START_READ,

        WAIT_READ_ADDRESS,

        READ_DATA,

        COMPLETE,

        ERROR
    };

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Transaction
    ///////////////////////////////////////////////////////////////////////////////////////////////

    Transaction _transaction =
        Transaction::NONE;

    State _state =
        State::IDLE;

    Result _result =
        Result::NONE;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Address
    ///////////////////////////////////////////////////////////////////////////////////////////////

    uint8_t _address = 0;

    uint8_t _register = 0;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Buffers
    ///////////////////////////////////////////////////////////////////////////////////////////////

    uint8_t* _readBuffer = nullptr;

    const uint8_t* _writeBuffer = nullptr;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Transfer
    ///////////////////////////////////////////////////////////////////////////////////////////////

    uint8_t _length = 0;

    uint8_t _index = 0;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Timing
    ///////////////////////////////////////////////////////////////////////////////////////////////

    uint32_t _stateStart_us = 0;

    uint32_t _frequency = 100000UL;

    static constexpr uint32_t STATE_TIMEOUT_US = 5000UL;

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Internal helpers
    ///////////////////////////////////////////////////////////////////////////////////////////////

    void setState(State state);

    bool timedOut() const;

    bool checkHardwareError();

    void complete();

    void fail(Result result);

    ///////////////////////////////////////////////////////////////////////////////////////////////
    // Peripheral
    ///////////////////////////////////////////////////////////////////////////////////////////////

    void initialisePeripheral();

    void recoverPeripheral();
};